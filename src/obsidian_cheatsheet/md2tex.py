"""Convert Obsidian cheat-sheet notes into the LaTeX chapters the sheet inputs.

Write the notes in Obsidian, run ``just cheatsheet-sync``, get typeset LaTeX.
One note becomes one ``chapters/<slug>.tex``; the notes are inputted in
filename order, so a numeric prefix (``01 Basics.md``) fixes the column order.

Markdown dialect, as Obsidian writes it:

===========================  ==========================================
``# / ## / ###``             ``\\section`` / ``\\subsection`` / ``\\subsubsection``
``$x$`` and ``$$x$$``        ``$x$`` and ``\\[x\\]``, contents verbatim
``- item`` / ``1. item``     ``itemize`` / ``enumerate``, nested by indent
``**b**``, ``*i*``/``_i_``   ``\\textbf``, ``\\emph``
``==h==``, ``<u>u</u>``      ``\\underline``
``` ``code`` ```             ``\\texttt``
``> quote``                  the ``key`` environment (centred key result)
pipe table                   ``tabular``, header row bold, alignment kept
``---`` on its own           ``\\columnbreak``
``%%c%%``, ``<!--c-->``      dropped, however many lines they span
``[[note|alias]]``           the alias text; ``![[embed]]`` is dropped
===========================  ==========================================

Everything outside maths is escaped for LaTeX except the backslash, so a raw
``\\Sum{a}{b}{c}`` typed in a note still reaches the PDF as a macro call.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HEADER = "% generated by md2tex.py — edit the Obsidian note, not this file\n"
ROOT_MAGIC = "% !TeX root = ../main.tex\n"

ROOT = Path(__file__).resolve().parents[2]
NOTES_DEFAULT = ROOT / "examples/notes"
OUT_DEFAULT = ROOT / "cheatsheet/chapters"

HEADINGS = ["section", "subsection", "subsubsection"]

# Text-mode specials. The backslash is deliberately absent: notes are allowed
# to carry raw LaTeX, which is the whole point of the macro layer.
ESCAPES = {
    "&": r"\&",
    "%": r"\%",
    "#": r"\#",
    "$": r"\$",
    "_": r"\_",
    "^": r"\textasciicircum{}",
    "~": r"\textasciitilde{}",
}

SENTINEL = "\x00{}\x00"
ORDERED = re.compile(r"^(\s*)\d+[.)]\s+(.*)$")
BULLET = re.compile(r"^(\s*)[-*+]\s+(.*)$")
HEADING = re.compile(r"^(#{1,6})\s+(.*)$")
COMMENT = re.compile(r"%%.*?%%|<!--.*?-->", re.DOTALL)
TABLE_RULE = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")


def _split_frontmatter(text: str) -> str:
    if not text.startswith("---\n"):
        return text
    end = text.find("\n---\n", 4)
    return text[end + 5 :] if end != -1 else text


def _protect(text: str) -> tuple[str, list[str]]:
    """Pull maths and code out of the stream so nothing else rewrites them."""
    kept: list[str] = []

    def stash(replacement: str) -> str:
        kept.append(replacement)
        return SENTINEL.format(len(kept) - 1)

    def display(m: re.Match[str]) -> str:
        return stash("\\[" + m.group(1).strip("\n") + "\\]")

    def inline(m: re.Match[str]) -> str:
        return stash("$" + m.group(1) + "$")

    def code(m: re.Match[str]) -> str:
        return stash("\\texttt{" + _escape(m.group(1)) + "}")

    def figure(m: re.Match[str]) -> str:
        return stash("\\input{figures/" + m.group(1) + "}")

    # An embed named fig-* is a TikZ diagram kept in cheatsheet/figures/. It is
    # stashed rather than rewritten later because _inline escapes what it emits.
    text = re.sub(r"!\[\[(fig-[\w-]+)\]\]", figure, text)
    text = re.sub(r"\\\$", lambda _: stash(r"\$"), text)
    text = re.sub(r"\$\$(.+?)\$\$", display, text, flags=re.DOTALL)
    text = re.sub(r"\$(.+?)\$", inline, text, flags=re.DOTALL)
    text = re.sub(r"`([^`]+)`", code, text)
    return text, kept


def _restore(text: str, kept: list[str]) -> str:
    return re.sub("\x00(\\d+)\x00", lambda m: kept[int(m.group(1))], text)


def _escape(text: str) -> str:
    return "".join(ESCAPES.get(c, c) for c in text)


def _inline(text: str) -> str:
    """Markdown emphasis to LaTeX, on a span with maths already stashed."""
    text = re.sub(r"!\[\[[^\]]*\]\]", "", text)
    text = re.sub(r"\[\[([^\]|]*)\|([^\]]*)\]\]", r"\2", text)
    text = re.sub(r"\[\[([^\]]*)\]\]", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)

    # A nested span comes back already escaped, so it is held aside rather than
    # left in the stream: the trailing _escape would otherwise turn its \& into
    # \\& and the TeX would break on the alignment tab.
    done: list[str] = []

    def keep(markup: str) -> str:
        done.append(markup)
        return f"\x01{len(done) - 1}\x01"

    # Emphasis markers are matched before escaping, so the escape pass never
    # sees the underscores that _this_ spelling of italics uses.
    def wrap(command: str):
        def replace(m: re.Match[str]) -> str:
            return keep(f"\\{command}{{{_inline(m[1])}}}")

        return replace

    text = re.sub(r"\*\*(.+?)\*\*", wrap("textbf"), text)
    text = re.sub(r"==(.+?)==", wrap("underline"), text)
    text = re.sub(r"<u>(.+?)</u>", wrap("underline"), text)
    text = re.sub(r"(?<!\w)\*(.+?)\*", wrap("emph"), text)
    text = re.sub(r"(?<!\w)_(.+?)_(?!\w)", wrap("emph"), text)
    return re.sub("\x01(\\d+)\x01", lambda m: done[int(m[1])], _escape(text))


def _columns(rule: str) -> str:
    spec = ""
    for cell in [c.strip() for c in rule.strip().strip("|").split("|")]:
        if cell.startswith(":") and cell.endswith(":"):
            spec += "c"
        elif cell.endswith(":"):
            spec += "r"
        else:
            spec += "l"
    return spec


def _row(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


class Converter:
    """Line-driven block parser; inline formatting is delegated to _inline."""

    def __init__(self) -> None:
        self.out: list[str] = []
        self.lists: list[tuple[str, int]] = []
        self.para: list[str] = []

    def convert(self, text: str) -> str:
        text, kept = _protect(COMMENT.sub("", _split_frontmatter(text)))
        lines = text.split("\n")
        i = 0
        while i < len(lines):
            i = self._line(lines, i)
        self._flush()
        self._close_lists(0)
        body = "\n".join(self.out).strip("\n")
        return _restore(body, kept) + "\n"

    # -- blocks ----------------------------------------------------------
    def _line(self, lines: list[str], i: int) -> int:
        line = lines[i]

        if not line.strip():
            self._flush()
            self._close_lists(0)
            return i + 1

        if line.strip() in {"---", "***", "___"}:
            self._flush()
            self._close_lists(0)
            self.out += ["", "\\columnbreak", ""]
            return i + 1

        if m := HEADING.match(line):
            self._flush()
            self._close_lists(0)
            level = min(len(m[1]), len(HEADINGS)) - 1
            self.out += ["", f"\\{HEADINGS[level]}{{{_inline(m[2])}}}", ""]
            return i + 1

        if line.lstrip().startswith(">"):
            return self._quote(lines, i)

        if "|" in line and i + 1 < len(lines) and TABLE_RULE.match(lines[i + 1]):
            return self._table(lines, i)

        ordered = ORDERED.match(line)
        if m := (ordered or BULLET.match(line)):
            self._flush()
            self._item("enumerate" if ordered else "itemize", len(m[1]), m[2])
            return i + 1

        if self.lists:
            # A bare continuation line belongs to the item above it.
            self.out[-1] += " " + _inline(line.strip())
            return i + 1

        self.para.append(line.strip())
        return i + 1

    def _quote(self, lines: list[str], i: int) -> int:
        self._flush()
        self._close_lists(0)
        body: list[str] = []
        while i < len(lines) and lines[i].lstrip().startswith(">"):
            body.append(lines[i].lstrip().removeprefix(">").strip())
            i += 1
        self.out += [
            "\\begin{key}",
            _inline(" ".join(body).strip()),
            "\\end{key}",
            "",
        ]
        return i

    def _table(self, lines: list[str], i: int) -> int:
        self._flush()
        self._close_lists(0)
        header = _row(lines[i])
        spec = _columns(lines[i + 1])
        i += 2
        rows: list[list[str]] = []
        while i < len(lines) and "|" in lines[i] and lines[i].strip():
            rows.append(_row(lines[i]))
            i += 1

        def render(cells: list[str], *, bold: bool = False) -> str:
            out = [_inline(c) for c in cells]
            if bold:
                out = [f"\\textbf{{{c}}}" for c in out]
            return " & ".join(out) + r" \\"

        self.out += [
            "\\begin{center}",
            f"\\begin{{tabular}}{{{spec}}}",
            render(header, bold=True),
            "\\hline",
            *[render(r) for r in rows],
            "\\end{tabular}",
            "\\end{center}",
            "",
        ]
        return i

    # -- lists -----------------------------------------------------------
    def _item(self, kind: str, indent: int, text: str) -> None:
        while len(self.lists) > 1 and self.lists[-1][1] > indent:
            self._close_lists(len(self.lists) - 1)
        if not self.lists or self.lists[-1][1] < indent:
            self.out.append(f"\\begin{{{kind}}}")
            self.lists.append((kind, indent))
        elif self.lists[-1][0] != kind:
            self.out.append(f"\\end{{{self.lists[-1][0]}}}")
            self.out.append(f"\\begin{{{kind}}}")
            self.lists[-1] = (kind, indent)
        self.out.append(f"  \\item {_inline(text)}")

    def _close_lists(self, depth: int) -> None:
        while len(self.lists) > depth:
            kind, _ = self.lists.pop()
            self.out.append(f"\\end{{{kind}}}")

    def _flush(self) -> None:
        if self.para:
            self.out += [_inline(" ".join(self.para)), ""]
            self.para = []


def convert(text: str) -> str:
    return Converter().convert(text)


def _slug(stem: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", stem.lower()).strip("-")


def sync(notes: Path, out: Path) -> list[Path]:
    """Regenerate out/ from notes/ and rewrite the chapters/all.tex manifest."""
    out.mkdir(parents=True, exist_ok=True)
    for stale in out.glob("*.tex"):
        if stale.read_text().startswith(HEADER):
            stale.unlink()

    written: list[Path] = []
    for note in sorted(notes.glob("*.md")):
        target = out / f"{_slug(note.stem)}.tex"
        target.write_text(HEADER + ROOT_MAGIC + "\n" + convert(note.read_text()))
        written.append(target)

    inputs = "\n".join(f"\\input{{chapters/{p.stem}}}" for p in written)
    (out / "all.tex").write_text(HEADER + ROOT_MAGIC + "\n" + inputs + "\n")
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description="Obsidian notes -> cheat-sheet LaTeX")
    parser.add_argument("--notes", type=Path, default=NOTES_DEFAULT)
    parser.add_argument("--out", type=Path, default=OUT_DEFAULT)
    args = parser.parse_args()

    if not args.notes.is_dir():
        print(f"no such notes directory: {args.notes}", file=sys.stderr)
        return 1

    written = sync(args.notes, args.out)
    for path in written:
        print(f"{path.name}")
    print(f"{len(written)} note(s) → {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
